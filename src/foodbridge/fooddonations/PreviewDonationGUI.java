	public void showDonations(ArrayList<Donation> list) {
		previewTF.setText("");
		if (list.isEmpty()) {
			previewTF.setText("No donations found.");
			return;
		}
		for (Donation d : list) {
			previewTF.append(d.getSummary() + "\n\n"); // each object builds own summary
		}
		previewTF.setCaretPosition(0); // scrolls back to top
	}

